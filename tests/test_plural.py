from massmap.report import _plural


def test_russian_plural():
    f = lambda n: _plural(n, "цепочка", "цепочки", "цепочек")
    assert [f(n) for n in (1, 2, 4, 5, 11, 12, 21, 22, 25, 101, 111)] == [
        "цепочка", "цепочки", "цепочки", "цепочек", "цепочек", "цепочек",
        "цепочка", "цепочки", "цепочек", "цепочка", "цепочек",
    ]
